import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const functionsDir = dirname(fileURLToPath(import.meta.url));
const checkOnly = process.argv.includes("--check");
const handlers = [
  "createCallCandidate.js",
  "startCallFromCard.js",
];

function stripSharedExports(sharedSource) {
  const exportMarker = "\nmodule.exports = {";
  const exportStart = sharedSource.indexOf(exportMarker);
  if (exportStart === -1) {
    throw new Error("Cannot find shared module export block.");
  }
  return sharedSource.slice(0, exportStart).trimEnd();
}

function stripSharedRequire(handlerSource, handlerName) {
  const sharedRequirePattern = /^const\s+\{[\s\S]*?\}\s*=\s*require\("\.\/calle-shared"\);\n\n/;
  if (!sharedRequirePattern.test(handlerSource)) {
    throw new Error(`Cannot find shared require block in ${handlerName}.`);
  }
  return handlerSource.replace(sharedRequirePattern, "");
}

async function main() {
  const sharedSource = stripSharedExports(
    await readFile(join(functionsDir, "calle-shared.js"), "utf8")
  );
  const failures = [];

  for (const handler of handlers) {
    const handlerPath = join(functionsDir, handler);
    const bundlePath = join(functionsDir, handler.replace(/\.js$/, ".bundle.js"));
    const handlerSource = await readFile(handlerPath, "utf8");
    const bundledSource = `${[
      "// Generated by build-bundles.mjs. Do not edit directly.",
      sharedSource,
      stripSharedRequire(handlerSource, handler).trimEnd(),
    ].join("\n\n")}\n`;

    if (checkOnly) {
      let currentSource = "";
      try {
        currentSource = await readFile(bundlePath, "utf8");
      } catch {
        failures.push(`${bundlePath} is missing.`);
        continue;
      }
      if (currentSource !== bundledSource) {
        failures.push(`${bundlePath} is out of date.`);
      }
    } else {
      await writeFile(bundlePath, bundledSource, "utf8");
    }
  }

  if (failures.length > 0) {
    throw new Error(`Function bundles are not current:\n${failures.join("\n")}`);
  }
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
