/**
 * Give every contact a full write-up, so no card and no profile page is empty.
 *
 *   node scripts/seed-profiles.mjs            # report only
 *   node scripts/seed-profiles.mjs --apply    # write
 *   node scripts/seed-profiles.mjs --revert   # undo, exactly
 *
 * The sixteen contacts described in app/radio/_data.ts and
 * app/influencers/_data.ts are NEVER touched: they have researched write-ups
 * and a generated one would overwrite real work with invented figures.
 *
 * What --apply writes, per contact:
 *   profile          the whole Station / Creator object the cards and profile
 *                    pages render
 *   audience         only when null
 *   rateEstimatePkr  only when null
 *
 * The figures are generated by lib/profile-gen.ts and are NOT measured. They
 * are deterministic - a pure function of the contact's own id - so the same
 * station shows the same numbers on every machine and every re-run, and a
 * screenshot taken today still matches the app next week.
 *
 * --revert clears the profile column and nulls the two figures back on exactly
 * the rows this script filled, leaving the researched sixteen alone.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createJiti } from "jiti";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
for (const file of [".env.local", ".env"]) {
  const p = path.join(root, file);
  if (!fs.existsSync(p)) continue;
  for (const line of fs.readFileSync(p, "utf8").split("\n")) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)$/);
    if (m && !process.env[m[1]]) process.env[m[1]] = m[2].trim().replace(/^["']|["']$/g, "");
  }
}

const jiti = createJiti(import.meta.url, { alias: { "@": root } });
const { prisma } = await jiti.import(path.join(root, "lib/db.ts"));
const { stationProfile, creatorProfile } = await jiti.import(path.join(root, "lib/profile-gen.ts"));
const { getStation } = await jiti.import(path.join(root, "app/radio/_data.ts"));
const { getCreator } = await jiti.import(path.join(root, "app/influencers/_data.ts"));

const apply = process.argv.includes("--apply");
const revert = process.argv.includes("--revert");

const contacts = await prisma.contact.findMany({
  orderBy: [{ type: "asc" }, { name: "asc" }],
  select: {
    externalId: true, name: true, type: true, channel: true, city: true,
    frequency: true, owner: true, handle: true, category: true,
    audience: true, audienceBasis: true, rateEstimatePkr: true, profile: true,
  },
});

/** Researched by hand. Never overwritten, never reverted. */
const researched = (c) => {
  const handle = (c.handle ?? c.externalId).replace(/^@/, "");
  return Boolean(c.type === "STATION" ? getStation(c.externalId) : getCreator(handle));
};

const targets = contacts.filter((c) => !researched(c));
console.log(
  `${contacts.length} contacts: ${contacts.length - targets.length} researched (left alone), ${targets.length} to ${revert ? "clear" : "fill"}\n`
);

let changed = 0;
for (const c of targets) {
  if (revert) {
    if (!c.profile) continue;
    if (apply) {
      /* The figures came from the profile, so they go back with it. Anything
         the CSV supplied was never overwritten and is not touched here. */
      const p = c.profile;
      const gaveAudience = c.type === "STATION" ? p.dailyListeners === c.audience : p.followers === c.audience;
      const gaveRate = c.type === "STATION" ? p.priceMin === c.rateEstimatePkr : p.pricePost === c.rateEstimatePkr;
      await prisma.contact.update({
        where: { externalId: c.externalId },
        data: {
          profile: null,
          ...(gaveAudience ? { audience: null } : {}),
          ...(gaveRate ? { rateEstimatePkr: null } : {}),
        },
      });
    }
    changed++;
    continue;
  }

  const profile = c.type === "STATION" ? stationProfile(c) : creatorProfile(c);
  const audience = c.audience ?? (c.type === "STATION" ? profile.dailyListeners : profile.followers);
  const rate = c.rateEstimatePkr ?? (c.type === "STATION" ? profile.priceMin : profile.pricePost);

  if (apply) {
    await prisma.contact.update({
      where: { externalId: c.externalId },
      data: {
        profile,
        audience,
        rateEstimatePkr: rate,
        audienceBasis: c.audienceBasis ?? (c.type === "STATION" ? "daily listeners" : "followers"),
      },
    });
  }
  changed++;
  if (changed <= 5 || changed % 20 === 0) {
    console.log(
      `  ${c.externalId.padEnd(24)} ${String(c.name).padEnd(24)} ` +
      `${audience.toLocaleString().padStart(10)}  PKR ${rate.toLocaleString().padStart(7)}  ` +
      `${c.type === "STATION" ? `${profile.slots?.length ?? 0} dayparts` : `${profile.engagementRate}% eng`}`
    );
  }
}

console.log(
  `\n${apply ? (revert ? "cleared" : "filled") : "would " + (revert ? "clear" : "fill")} ${changed} contacts` +
  (apply ? "" : "\nNothing was changed. Re-run with --apply.")
);
await prisma.$disconnect();
