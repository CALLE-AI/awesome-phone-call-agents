function interpolate(value: string, values?: TranslationValues) {
  if (!values) return value;
  return value.replace(/\{(\w+)\}/g, (match, key: string) => String(values[key] ?? match));
}

export function translateText(language: UiLanguage, source: string, values?: TranslationValues) {
  const translated = language === "en" ? english[source] || source : source;
  return interpolate(translated, values);
}

export function localizeApiMessage(language: UiLanguage, message: string) {
  if (language === "ar" || !message) return message;
  if (english[message]) return english[message];
  let localized = message;
  for (const [arabic, translation] of serverPhraseReplacements) localized = localized.replace(arabic, translation);
  return localized;
}

type I18nContextValue = {
  language: UiLanguage;
  direction: "rtl" | "ltr";
  locale: "ar-SA" | "en-US";
  setLanguage: (language: UiLanguage) => void;
  toggleLanguage: () => void;
  t: Translator;
  localizeMessage: (message: string) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<UiLanguage>("ar");

  const setLanguage = useCallback((next: UiLanguage) => {
    setLanguageState(next);
    window.localStorage.setItem(STORAGE_KEY, next);
  }, []);

  useEffect(() => {
    const timer = window.setTimeout(() => {
      const saved = window.localStorage.getItem(STORAGE_KEY);
      if (saved === "ar" || saved === "en") setLanguageState(saved);
    }, 0);
    return () => window.clearTimeout(timer);
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
  }, [language]);

  const t = useCallback<Translator>((source, values) => translateText(language, source, values), [language]);
  const localizeMessage = useCallback((message: string) => localizeApiMessage(language, message), [language]);
  const value = useMemo<I18nContextValue>(() => ({
    language,
    direction: language === "ar" ? "rtl" : "ltr",
    locale: language === "ar" ? "ar-SA" : "en-US",
    setLanguage,
    toggleLanguage: () => setLanguage(language === "ar" ? "en" : "ar"),
    t,
    localizeMessage,
  }), [language, setLanguage, t, localizeMessage]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used within I18nProvider");
  return context;
}
